"""Write src/assets/symbolMetrics.ts: visible-art box and fill of each symbol PNG.
Run after changing any PNG: python scripts/symbol_metrics.py  (needs numpy, pillow)"""
from pathlib import Path
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
rows = []
for f in sorted((ROOT / 'public/assets/symbols').glob('*.png')):
    a = np.asarray(Image.open(f).convert('RGBA'))[..., 3].astype(float) / 255
    ys, xs = np.where(a > 10 / 255)
    x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    fill = a[y0:y1, x0:x1].sum() / ((x1 - x0) * (y1 - y0))
    rows.append(f"  '{f.stem}': {{ size: {a.shape[1]}, x: {x0}, y: {y0}, w: {x1 - x0}, h: {y1 - y0}, fill: {fill:.3f} }},")
out = ROOT / 'src/assets/symbolMetrics.ts'
out.write_text(
    "// Generated by scripts/symbol_metrics.py — visible-art box inside each square PNG.\n"
    "import type { SymbolId } from './symbols'\n\n"
    "export type SymbolMetric = { size: number; x: number; y: number; w: number; h: number; fill: number }\n\n"
    "export const SYMBOL_METRICS: Record<SymbolId, SymbolMetric> = {\n" + "\n".join(rows) + "\n}\n"
)
print(out.read_text())
